"""Sprite sheet: the creatures at several sizes, a glow and the foam flecks."""
import numpy as np
from PIL import Image
import art
from packing import bgr15, pack_tile

KINDS = ['surfer', 'fin', 'turtle', 'board', 'shark', 'jelly']
DRAW = dict(surfer=art.draw_surfer, fin=art.draw_fin, turtle=art.draw_turtle,
            board=art.draw_board, shark=art.draw_shark, jelly=art.draw_jelly)
# (height in px, box): a 16-px box is one sprite, a 32-px box is four, 64 is one big one
SCALES = [(9, 16), (15, 16), (24, 32), (32, 32), (54, 64)]
NSCALE = {'surfer': 5}          # the others stop at 32 px
SHEET = 16                      # tiles across


def glow_image():
    """A 32x32 dithered glow: white heart, pale cyan halo."""
    im = np.zeros((32, 32), dtype=np.int32)
    yy, xx = np.mgrid[0:32, 0:32]
    r = np.hypot(xx - 15.5, yy - 15.5)
    bayer = np.array([[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]) / 16.0
    th = np.tile(bayer, (8, 8))
    core = r < 3.2
    mid = (r < 8.0) & (th * 8 + 3.2 > r - 0.0)
    halo = (r < 15.5) & (th < np.clip((15.5 - r) / 10.0, 0, 1) * 0.9)
    im[halo] = 3
    im[(r < 11) & (th < np.clip((11 - r) / 5.0, 0, 1))] = 2
    im[(r < 6) & (th < np.clip((6.5 - r) / 3.5, 0, 1) * 1.1)] = 1
    im[core] = 1
    return im


def build(out):
    sheet = np.zeros((32 * 8, SHEET * 8), dtype=np.int32)
    pals = np.zeros((8, 16, 3))
    frames = {}                         # (kind, scale) -> [(dx, dy, tile, flags)]
    def blit(img, row, col):
        sheet[row * 8:row * 8 + img.shape[0], col * 8:col * 8 + img.shape[1]] = img
    for k, name in enumerate(KINDS):
        big = DRAW[name]()
        ns = NSCALE.get(name, 4)
        tiles_rgba = [art.squeeze(big, px, box) for px, box in SCALES[:ns]]
        # one 15-colour palette for all sizes of this creature
        pix = np.concatenate([t[t[:, :, 3] > 0][:, :3] for t in tiles_rgba])
        q = Image.fromarray(pix.astype(np.uint8).reshape(-1, 1, 3)).quantize(15, method=Image.MEDIANCUT, dither=Image.NONE)
        pal = np.array(q.getpalette()[:45]).reshape(15, 3) / 255.0
        pals[k, 1:16] = pal[:15]
        for s, t in enumerate(tiles_rgba):
            box = SCALES[s][1]
            rgb = t[:, :, :3] / 255.0
            d = ((rgb[:, :, None, :] - pal[None, None, :, :]) ** 2).sum(3)
            idx = d.argmin(2) + 1
            idx = np.where(t[:, :, 3] > 0, idx, 0)
            row0 = 4 * k
            if box == 16:
                col = 8 + 2 * (s % 2)
                blit(idx, row0, col)
                n = row0 * 16 + col
                frames[(k, s)] = [(0, 0, n & 255, n >> 8)]
            elif box == 32:
                col = 4 * (s - 2)
                blit(idx, row0, col)
                n = row0 * 16 + col
                fl = n >> 8
                frames[(k, s)] = [(0, 0, n & 255, fl), (16, 0, (n + 2) & 255, fl), (0, 16, (n + 32) & 255, fl), (16, 16, (n + 34) & 255, fl)]
            else:
                blit(idx, 24, 0)
                n = 24 * 16
                frames[(k, s)] = [(0, 0, n & 255, (n >> 8) | 2)]
        for s in range(ns, 5):
            frames[(k, s)] = frames[(k, ns - 1)]
    # glow and foam flecks share palette 6
    pals[6, 1] = (1.0, 1.0, 1.0)
    pals[6, 2] = (0.78, 1.0, 0.96)
    pals[6, 3] = (0.42, 0.86, 0.80)
    pals[6, 4] = (0.92, 0.98, 0.96)
    g = glow_image()
    blit(g, 24, 8)
    gn = 24 * 16 + 8
    fleck = []
    for v, (r, c) in enumerate(((24, 12), (24, 14), (26, 12))):
        f = np.zeros((16, 16), dtype=np.int32)
        if v == 0:
            f[7:9, 7:9] = 4
        elif v == 1:
            f[6:10, 7:9] = 1
            f[7:9, 6:10] = 1
        else:
            f[7:9, 5:11] = 2
            f[6:10, 7:9] = 1
        blit(f, r, c)
        fleck.append(r * 16 + c)
    chars = b''.join(pack_tile(sheet[ty * 8:ty * 8 + 8, tx * 8:tx * 8 + 8], 4) for ty in range(32) for tx in range(SHEET))
    open(f'{out}/obj_chars.bin', 'wb').write(chars)
    words = [bgr15(pals[p, i]) if i else 0 for p in range(8) for i in range(16)]
    open(f'{out}/obj_pal.bin', 'wb').write(np.array(words, dtype='<u2').tobytes())
    np.save(f'{out}/sheet.npy', sheet)
    np.save(f'{out}/sheet_pal.npy', pals)
    # the metasprite tables for ca65
    L = ['; generated by build_sprites.py', 'NSCALES = 5', 'NKINDS = 6']
    L.append('frame_ptrs:')
    for k in range(len(KINDS)):
        L.append('    .word ' + ', '.join(f'.loword(frm_{k}_{s})' for s in range(5)))
    for k in range(len(KINDS)):
        for s in range(5):
            f = frames[(k, s)]
            L.append(f'frm_{k}_{s}:  .byte {len(f)}, {SCALES[s][1] if (k, s) in frames and s < NSCALE.get(KINDS[k], 4) else SCALES[min(s, NSCALE.get(KINDS[k], 4) - 1)][1]}')
            for dx, dy, t, fl in f:
                L.append(f'    .byte {dx}, {dy}, {t}, {fl}')
    L.append(f'GLOW_TILE = {gn & 255}')
    L.append(f'GLOW_FLAGS = {gn >> 8}')
    L.append('fleck_tiles: .byte ' + ', '.join(str(n & 255) for n in fleck))
    L.append('fleck_flags: .byte ' + ', '.join(str(n >> 8) for n in fleck))
    open(f'{out}/frames.inc', 'w').write('\n'.join(L) + '\n')
    print(f'sprites: {len(chars) // 32} tiles')
    return sheet, pals
