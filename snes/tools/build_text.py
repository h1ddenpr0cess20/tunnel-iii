"""BG3: the font, big title letters and the nose of the board (2bpp)."""
import numpy as np
from PIL import Image, ImageDraw, ImageFont
from packing import bgr15, pack_tile

FONT = '/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf'
CHARS = " 0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ.,!-:'/?"      # tile n is CHARS[n]
NOSE_FIRST = 48
NOSE_W, NOSE_H = 6, 8
BIG_FIRST = 96
BIG_LETTERS = "NEVRDIGTULWPO"                                  # 13 letters x 4 tiles = 52
TEXT_PAL = {0: [(0.0, 0.0, 0.0), (1.0, 1.0, 1.0), (0.62, 0.90, 0.86), (0.02, 0.10, 0.12)],
            1: [(0, 0, 0), (1.0, 0.84, 0.36), (0.86, 0.56, 0.12), (0.10, 0.06, 0.02)],
            2: [(0, 0, 0), (0.78, 0.97, 0.90), (0.30, 0.72, 0.70), (0.06, 0.30, 0.34)],
            3: [(0, 0, 0), (1.0, 0.62, 0.52), (0.86, 0.26, 0.22), (0.16, 0.04, 0.04)]}


V8 = ["11000110", "11000110", "01100110", "01101100", "00111100", "00111000", "00010000", "00000000"]


def glyph(ch, size, cell):
    if ch == 'V' and cell == 8:
        a = np.array([[c == '1' for c in r] for r in V8])
        out = np.zeros((8, 8), dtype=np.int32)
        sh = np.zeros_like(a)
        for dy, dx in ((1, 0), (0, 1), (1, 1)):
            sh[dy:, dx:] |= a[:8 - dy, :8 - dx]
        out[sh] = 3
        out[a] = 1
        return out
    f = ImageFont.truetype(FONT, size)
    im = Image.new('L', (cell, cell), 0)
    d = ImageDraw.Draw(im)
    d.fontmode = '1'
    bb = d.textbbox((0, 0), ch, font=f)
    d.text(((cell - (bb[2] - bb[0])) // 2 - bb[0], (cell - (bb[3] - bb[1])) // 2 - bb[1]), ch, font=f, fill=255)
    a = np.array(im) > 127
    # fill 1 with a dark outline below and right (3), so it reads over bright water
    out = np.zeros((cell, cell), dtype=np.int32)
    sh = np.zeros_like(a)
    for dy, dx in ((1, 0), (0, 1), (1, 1)):
        sh[dy:, dx:] |= a[:cell - dy, :cell - dx]
    out[sh] = 3
    out[a] = 1
    return out


def nose():
    """The board's nose seen from above and behind: a rounded point, mint with teal stripes."""
    w, h = NOSE_W * 8, NOSE_H * 8
    im = np.zeros((h, w), dtype=np.int32)
    yy, xx = np.mgrid[0:h, 0:w]
    cx = w / 2 - 0.5
    # half-width grows from a point at the top, like an ogive
    t = np.clip((yy - 1) / (h - 1.0), 0, 1)
    half = (w / 2 - 1.5) * np.sqrt(np.clip(1 - (1 - t) ** 2.4, 0, 1)) * (0.62 + 0.38 * t)
    inside = np.abs(xx - cx) <= half
    im[inside] = 1
    edge = inside & ((np.abs(xx - cx) > half - 1.4))
    im[edge] = 3
    # shade the right-hand side with a dither
    shade = inside & (xx > cx + 3) & (((xx + yy) & 1) == 0)
    im[shade] = 2
    # teal stripes, then the stringer down the middle
    for y0 in (int(h * 0.52), int(h * 0.64)):
        im[(yy >= y0) & (yy < y0 + 3) & inside] = 2
    im[(np.abs(xx - cx) < 0.7) & inside & (yy > 3)] = 3
    return im


def build(out):
    tiles = [np.zeros((8, 8), dtype=np.int32) for _ in range(256)]
    for n, ch in enumerate(CHARS):
        if ch != ' ':
            tiles[n] = glyph(ch, 8, 8)
    nz = nose()
    for ty in range(NOSE_H):
        for tx in range(NOSE_W):
            tiles[NOSE_FIRST + ty * NOSE_W + tx] = nz[ty * 8:ty * 8 + 8, tx * 8:tx * 8 + 8]
    for i, ch in enumerate(BIG_LETTERS):
        g = glyph(ch, 17, 16)
        for q, (oy, ox) in enumerate(((0, 0), (0, 8), (8, 0), (8, 8))):
            tiles[BIG_FIRST + 4 * i + q] = g[oy:oy + 8, ox:ox + 8]
    open(f'{out}/bg3_chars.bin', 'wb').write(b''.join(pack_tile(t, 2) for t in tiles))
    # character -> tile, for the print routine
    cmap = bytearray(128)
    for n, ch in enumerate(CHARS):
        cmap[ord(ch)] = n
    open(f'{out}/font_map.bin', 'wb').write(bytes(cmap))

    def strip(text, pal):
        """two rows of map words for big text"""
        rows = [[], []]
        for ch in text:
            if ch == ' ':
                for r in rows:
                    r += [0, 0]
                continue
            i = BIG_LETTERS.index(ch)
            t = BIG_FIRST + 4 * i
            rows[0] += [t | (pal << 10) | 0x2000, t + 1 | (pal << 10) | 0x2000]
            rows[1] += [t + 2 | (pal << 10) | 0x2000, t + 3 | (pal << 10) | 0x2000]
        return rows
    strips = {'neverending': strip('NEVERENDING', 0), 'tunnel': strip('TUNNEL', 0), 'iii': strip('III', 1),
              'wipeout': strip('WIPEOUT', 3)}
    blob = bytearray()
    L = ['; generated by build_text.py']
    for name, rows in strips.items():
        L.append(f'strip_{name}: .word {len(rows[0])}')
        for r in rows:
            L.append('    .word ' + ', '.join(str(v) for v in r))
    nose_words = [(NOSE_FIRST + ty * NOSE_W + tx) | (2 << 10) | (1 << 13) for ty in range(NOSE_H) for tx in range(NOSE_W)]
    L.append('nose_map: .word ' + ', '.join(str(v) for v in nose_words))
    L.append(f'NOSE_W = {NOSE_W}')
    L.append(f'NOSE_H = {NOSE_H}')
    open(f'{out}/text.inc', 'w').write('\n'.join(L) + '\n')
    pals = [bgr15(c) for p in range(4) for c in TEXT_PAL[p]]
    open(f'{out}/text_pal.bin', 'wb').write(np.array(pals, dtype='<u2').tobytes())
    np.save(f'{out}/bg3_preview.npy', np.array(tiles))
    print('bg3: font + nose + big letters')
